DROP_ROW = "11항 정정사항"   # 정정사항 슬라이드 삭제로 고아가 된 인용 행
for slide in prs.slides:
    for sh in slide.shapes:
        if not sh.has_table:
            continue
        t = sh.table
        if t.cell(0, 0).text.strip() != "구  분":
            continue
        if "출  처" not in t.cell(0, 1).text:
            continue
        for tr in list(t._tbl.tr_lst[1:]):
            txt = "".join(tr.itertext())
            if DROP_ROW in txt:
                t._tbl.remove(tr)
        for ri in range(1, len(t.rows)):
            c = t.cell(ri, 2)
            k = c.text.strip()
            if k in CELL_FIX:
                runs = [r for p in c.text_frame.paragraphs for r in p.runs]
                if runs:
                    runs[0].text = CELL_FIX[k]
                    for r in runs[1:]:
                        r.text = ""
            c2 = t.cell(ri, 1)
            if "p.18~19" in c2.text:
                runs = [r for p in c2.text_frame.paragraphs for r in p.runs]
